export function getSignBySlug(slug: string): ZodiacSign | undefined {
  return ZODIAC_SIGNS.find((s) => s.key === slug);
}

export function getSignContent(slug: string): SignContent | undefined {
  return SIGN_CONTENT[slug];
}
