/**
 * 검색어가 후보에 걸리는지 판단한다.
 *
 * "서울"로 "서울특별시"를, "경기"로 "경기도"를 찾을 수 있어야 하므로 단순
 * 부분 문자열 포함으로 본다. 한글 입력은 조합 중간 상태("서우ㄹ")를 거치는데,
 * 그 상태에서는 아무것도 걸리지 않고 조합이 끝나면 걸린다 — 초성 검색까지
 * 지원하면 코드가 크게 늘어나는 데 비해, 선택지가 최대 31개인 이 목록에서는
 * 이득이 거의 없다.
 */
export function matchesQuery(candidate: string, aliases: string[], query: string): boolean {
  const q = query.trim();
  if (q === "") return true;
  if (candidate.includes(q)) return true;
  return aliases.some((a) => a.includes(q));
}

/** 광역자치단체 목록에서 검색어에 걸리는 것만 남긴다. */
export function filterProvinces(query: string): Province[] {
  return PROVINCES.filter((p) => matchesQuery(p.name, p.aliases ?? [], query));
}

/** 특정 광역자치단체의 시·군·구 중 검색어에 걸리는 것만 남긴다. */
export function filterDistricts(provinceName: string, query: string): string[] {
  const province = PROVINCES.find((p) => p.name === provinceName);
  if (!province) return [];
  return province.districts.filter((d) => matchesQuery(d, [], query));
}

/** 백엔드 지오코딩에 넘길, 그리고 화면에 보여줄 최종 표기. */
export function formatPlace(province: string, district: string | null): string {
  return district ? `${province} ${district}` : province;
}
