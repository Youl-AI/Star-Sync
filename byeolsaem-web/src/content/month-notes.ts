/**
 * 달마다 손으로 쓰는 한 문단.
 *
 * 월별 화면(/calendar/YYYY/MM, /ephemeris/YYYY/MM)은 열두 장이 한 틀에서 나온다.
 * 그래서 서로 절반 이상이 같은 문장이고, 다른 절반은 날짜 숫자다(2026-09-05 실측:
 * 달력 두 달을 여덟 글자 단위로 비교하면 53%가 겹친다). 검색 엔진이 "틀 하나에
 * 값만 갈아 끼운 페이지"로 읽기 좋은 모양이고, 실제로 애드센스 심사에서 얇은
 * 콘텐츠로 걸린 자리다.
 *
 * 그래서 규칙을 하나로 정했다. **여기에 글이 있는 달만 색인한다.** 글이 없는 달은
 * `noindex`로 나가고 사이트맵에서도 빠진다 — 화면에서 사라지지는 않는다. 이전 달과
 * 다음 달 단추로 여전히 닿고, 자료도 그대로다. 검색 결과에만 내놓지 않을 뿐이다.
 *
 * 자동 생성 문장으로 이 칸을 채우지 않는다. 틀에서 나온 문장을 더 얹으면 겹침
 * 비율만 조금 낮아질 뿐 같은 문제를 더 긴 형태로 반복하게 된다.
 *
 * 새 달을 여는 절차: 그 달의 사건을 `monthEvents`로 확인하고, 아래에 두 문단을
 * 적는다. 달력 쪽은 그달 하늘의 성격을, 천문력 쪽은 표에서 무엇이 눈에 띄는지를
 * 쓴다. 같은 문장을 양쪽에 복사하면 두 페이지가 서로 중복이 된다.
 */

export interface MonthNote {
  /** /calendar/YYYY/MM 에 실린다. 그달 하늘의 성격. */
  calendar: string;
  /** /ephemeris/YYYY/MM 에 실린다. 표에서 눈에 띄는 것. */
  ephemeris: string;
}

