/** 이 달에 손으로 쓴 글이 있는가. 없으면 null — 색인 대상이 아니다. */
export function monthNote(year: number, month: number): MonthNote | null {
  return MONTH_NOTES[`${year}-${pad(month)}`] ?? null;
}

/** 색인해도 되는 달인가. 사이트맵과 각 화면의 robots가 같은 답을 쓴다. */
export function isIndexableMonth(year: number, month: number): boolean {
  return monthNote(year, month) !== null;
}
